 @Test fun npcOptionsPreserveAuthoritativeIndexUsingActualTspsReaderByteOrder(){
  // TSPS Reader.shortAddLE is BE+low128; Reader.shortAdd is LE+low128.
  val expected=listOf("4c000334","0c033400","22340300","4600b403","3980b403")
  for(op in 1..5){val action=nativeAction(net.rsprot.protocol.game.incoming.npcs.OpNpcV2(948,false,op,0))!!;assertContentEquals(hex(expected[op-1]),clientPacket(action.opcode,action.bytes,action.lengthBytes))}
 }
 private fun hex(s:String)=s.chunked(2).map{it.toInt(16).toByte()}.toByteArray()
 @Test fun widgetsAreValidatedAgainstNativeCacheIncludingNestedOpenSubMetadata(){
  val valid=setOf(0,22,(161 shl 16),(219 shl 16),(219 shl 16) or 2)
  configureWidgetComponents{it in valid}
  try {
   assertTrue(translateOutgoing(105,payload{writeInt(5857);text("Unarmed")}).isEmpty())
   assertEquals(1,translateOutgoing(105,payload{writeInt(22);text("valid")}).size)
   assertTrue(translateOutgoing(105,payload{writeInt(23);text("past group end")}).isEmpty())
   assertTrue(translateOutgoing(107,payload{writeInt(5857);writeShort(995);writeInt(1)}).isEmpty())
   val messages=translateOutgoing(103,payload{
    writeInt(161 shl 16);writeShort(219);writeByte(0);writeByte(0);writeByte(0)
    writeByte(2);writeInt(5857);writeInt((219 shl 16) or 2);writeByte(0);writeByte(0)
   })
   assertEquals(2,messages.size);assertIs<IfOpenSub>(messages[0]);assertIs<IfSetHide>(messages[1])
  } finally {configureWidgetComponents{true}}
 }
 @Test fun nativeVarpCapacityRejectsBrowserOverlayIdsOnEveryTranslationRoute(){
  val capacity=5996
  configureVarpCapacity(capacity)
  try {
   assertTrue(translateOutgoing(40,payload{writeShort(7998);writeByte(0)}).isEmpty())
   assertTrue(translateOutgoing(41,payload{writeShort(capacity);writeInt(1)}).isEmpty())
   assertEquals(1,translateOutgoing(41,payload{writeShort(capacity-1);writeInt(1)}).size)
   assertTrue(translateOutgoing(44,payload{writeShort(7998);writeLong(1)}).isEmpty())
   val state=TranslationState(mapOf(9 to intArrayOf(7998,0,1)))
   assertTrue(translateOutgoing(42,payload{writeShort(9);writeInt(1)},state).isEmpty())
   val open=translateOutgoing(103,payload{
    writeInt(161 shl 16);writeShort(219);writeByte(0)
    writeByte(1);writeShort(7998);writeInt(1);writeByte(0);writeByte(0);writeByte(0);writeByte(0)
   })
   assertEquals(1,open.size);assertIs<IfOpenSub>(open.single())
  } finally {configureVarpCapacity(Int.MAX_VALUE)}
 }
