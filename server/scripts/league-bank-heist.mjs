// Builds plugins/modes/data/league-bank-heist.json, Bank Heist's destinations (docs/leagues.md),
// from the cache's bank placements as scripts/dump-loc.ts lists them:
//
//   yarn dump:loc --json "Bank booth" "Bank Booth" "Bank chest" "Bank Chest" "Bank deposit box" "Bank Deposit Box" \
//     "Deposit box" "Deposit Box" "Grand Exchange booth" "Bank counter" "Bank table" "Open chest" "Chest" \
//     | node scripts/league-bank-heist.mjs > plugins/modes/data/league-bank-heist.json
//
// A bank loc counts when it has an option (a decorative or closed one has none); a loc named only
// "Chest" or "Open chest" counts when one of its options is Bank. Template copies (dump-loc's
// `template` rows, before the bridge-plane rule) are left out: the live placement is the other row.
// Placements within 12 tiles of any placement of a bank on the same plane are that bank (kinds:
// bank over bank chest over deposit box), kept at its first placement in map order; the relic
// lands on the nearest open tile from which the bank's floor can be walked. The same input always
// gives the same file.
import { createInterface } from "node:readline";

const CLUSTER = 12;
const GENERIC = new Set(["chest", "open chest"]);
const RANK = { bank: 3, "bank chest": 2, "deposit box": 1 };

const lines = [];
for await (const line of createInterface({ input: process.stdin })) if (line.startsWith("{")) lines.push(JSON.parse(line));

function counts(row) {
  if (row.template || !Array.isArray(row.ops) || row.ops.length === 0) return false;
  return !GENERIC.has(String(row.name).toLowerCase()) || row.ops.includes("Bank");
}

function kindOf(row) {
  const name = String(row.name).toLowerCase();
  if (name.includes("deposit")) return "deposit box";
  if (name.includes("chest")) return "bank chest";
  return "bank";
}

const placements = lines.filter(counts).sort((a, b) => a.z - b.z || a.x - b.x || a.y - b.y || a.id - b.id);

// Single linkage: a placement near any member of a bank joins it (and merges banks it bridges).
const banks = [];
for (const row of placements) {
  const point = { x: row.x, y: row.y };
  const near = banks.filter((bank) => bank.z === row.z && bank.members.some((member) => Math.abs(member.x - row.x) <= CLUSTER && Math.abs(member.y - row.y) <= CLUSTER));
  const kind = kindOf(row);
  if (near.length === 0) {
    banks.push({ x: row.x, y: row.y, z: row.z, kind, members: [point] });
    continue;
  }
  const [first, ...rest] = near;
  first.members.push(point);
  if (RANK[kind] > RANK[first.kind]) first.kind = kind;
  for (const other of rest) {
    first.members.push(...other.members);
    if (RANK[other.kind] > RANK[first.kind]) first.kind = other.kind;
    banks.splice(banks.indexOf(other), 1);
  }
}

const out = {
  $comment: "Bank Heist's destinations (docs/leagues.md): every bank, bank chest and deposit box in the cache's map, near ones merged. Generated by scripts/league-bank-heist.mjs from yarn dump:loc (the command is in the script); do not edit by hand, regenerate.",
  banks: banks.map(({ x, y, z, kind }) => ({ x, y, z, kind })),
};
process.stdout.write(`${JSON.stringify(out, null, 1).replace(/\{\n\s+"x": (\d+),\n\s+"y": (\d+),\n\s+"z": (\d+),\n\s+"kind": ("[^"]+")\n\s+\}/g, '{ "x": $1, "y": $2, "z": $3, "kind": $4 }')}\n`);
